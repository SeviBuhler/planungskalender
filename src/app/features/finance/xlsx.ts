// Minimal .xlsx writer: a zip (stored, not compressed) with one worksheet per table.
// Enough for plain tables with bold headers and CHF number format, no library needed.

export type Cell = string | number | null;

export interface Sheet {
  name: string; // max 31 characters, no []:*?/\
  columns: number[]; // column widths in characters
  rows: Cell[][];
  boldRows?: number[]; // indexes of rows shown bold (headings, totals)
}

const XML_HEAD = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n';

function escapeXml(text: string): string {
  return text.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
}

function columnName(index: number): string {
  let name = '';
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  return name;
}

// Style ids from styles.xml: 0 text, 1 number, 2 bold text, 3 bold number
function cellXml(value: Cell, ref: string, bold: boolean): string {
  if (value === null || value === '') return '';
  if (typeof value === 'number') return `<c r="${ref}" s="${bold ? 3 : 1}"><v>${value}</v></c>`;
  return `<c r="${ref}" t="inlineStr" s="${bold ? 2 : 0}"><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`;
}

function sheetXml(sheet: Sheet): string {
  const cols = sheet.columns.map((width, i) => `<col min="${i + 1}" max="${i + 1}" width="${width}" customWidth="1"/>`).join('');
  const rows = sheet.rows
    .map((row, r) => {
      const bold = sheet.boldRows?.includes(r) ?? false;
      return `<row r="${r + 1}">${row.map((value, c) => cellXml(value, `${columnName(c)}${r + 1}`, bold)).join('')}</row>`;
    })
    .join('');
  return `${XML_HEAD}<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><cols>${cols}</cols><sheetData>${rows}</sheetData></worksheet>`;
}

